/**
 * 6장 Q14: places the dart can land on — administrative districts with a centre coordinate.
 * The built-in list is 시·군·구 level (a starter); drop the public 행정동 CSV at
 * phone assets/regions.csv ("시도,시군구,읍면동,lat,lng" per line) and [load] replaces it.
