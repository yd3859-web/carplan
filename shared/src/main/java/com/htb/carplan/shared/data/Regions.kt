object Regions {
    data class Region(val sido: String, val sigungu: String, val dong: String?, val lat: Double, val lng: Double) {
        val fullName: String get() = listOfNotNull(sido, sigungu, dong).joinToString(" ")
    }

    @Volatile var all: List<Region> = builtIn()
        private set

    /** Replaces the list from CSV lines (header optional). Keeps the built-in list when the file is empty. */
    fun load(csvLines: List<String>) {
        val parsed = csvLines.mapNotNull { line ->
            val c = line.split(",").map { it.trim() }
            if (c.size < 5) return@mapNotNull null
            val lat = c[3].toDoubleOrNull() ?: return@mapNotNull null
            val lng = c[4].toDoubleOrNull() ?: return@mapNotNull null
            Region(c[0], c[1], c[2].ifBlank { null }, lat, lng)
        }
        if (parsed.isNotEmpty()) all = parsed
    }

    /** Back to the built-in list (tests, or when the CSV turns out broken). */
    fun reset() { all = builtIn() }

    val sidoNames: List<String> get() = all.map { it.sido }.distinct()

    /** Random pick inside the scope; NEAR = within [radiusKm] of the centre; REGION = one 시·도. */
    fun pick(scope: DartScope, centerLat: Double? = null, centerLng: Double? = null, region: String? = null, radiusKm: Double = 100.0, random: Random = Random.Default): Region? {
        val pool = when (scope) {
            DartScope.NATIONAL -> all
            DartScope.NEAR -> if (centerLat == null || centerLng == null) all else all.filter { RouteMath.metersBetween(centerLat, centerLng, it.lat, it.lng) <= radiusKm * 1000 }
            DartScope.REGION -> all.filter { it.sido == region }
        }
        return pool.randomOrNull(random)
    }

